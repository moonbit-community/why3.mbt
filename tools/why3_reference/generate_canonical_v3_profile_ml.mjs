import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');

function fail(message) {
  throw new Error(message);
}

function parseArguments(argv) {
  if (argv.length === 0) return { mode: 'stdout', path: null };
  if (argv.length !== 2 || !['--output', '--check'].includes(argv[0])) {
    fail(
      'usage: generate_canonical_v3_profile_ml.mjs ' +
      '[--output PATH | --check PATH]',
    );
  }
  return { mode: argv[0].slice(2), path: resolve(argv[1]) };
}

function readJson(path) {
  return JSON.parse(readFileSync(join(PROJECT_ROOT, path), 'utf8'));
}

function quoted(value) {
  if (!/^[0-9a-f]{64}$/u.test(value)) {
    fail(`expected a lowercase SHA-256 digest, got ${JSON.stringify(value)}`);
  }
  return JSON.stringify(value);
}

function render() {
  const profile = readJson('tools/contracts/semantic-profile-v3.json');
  const diagnostics = readJson('tools/contracts/diagnostics-v1.json');
  const schema = readJson('tools/contracts/canonical-schema-v3.json');
  if (profile.canonicalSchemaVersion !== 3 || schema.schemaVersion !== 3) {
    fail('canonical v3 profile inputs have incompatible versions');
  }
  return [
    '(********************************************************************)',
    '(* Generated by generate_canonical_v3_profile_ml.mjs. Do not edit.   *)',
    '(********************************************************************)',
    '',
    `let semantic_profile_sha256 = ${quoted(profile.semanticProfileSha256)}`,
    `let diagnostic_contract_sha256 = ${quoted(diagnostics.diagnosticContractSha256)}`,
    `let canonical_schema_sha256 = ${quoted(schema.canonicalSchemaSha256)}`,
    '',
  ].join('\n');
}

try {
  const arguments_ = parseArguments(process.argv.slice(2));
  const rendered = render();
  if (arguments_.mode === 'output') {
    writeFileSync(arguments_.path, rendered);
  } else if (arguments_.mode === 'check') {
    if (readFileSync(arguments_.path, 'utf8') !== rendered) {
      fail(`${arguments_.path} does not match the generated OCaml profile`);
    }
  } else {
    process.stdout.write(rendered);
  }
} catch (error) {
  process.stderr.write(`generate_canonical_v3_profile_ml: ${error.message}\n`);
  process.exitCode = 1;
}
