import {
  mkdirSync,
  readFileSync,
  readdirSync,
  realpathSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const SCRIPT_DIRECTORY = dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = resolve(SCRIPT_DIRECTORY, '..', '..');
const EXPECTED_COMMIT = '1343338d3bb1941c0d4f134283bb0790816113c4';
const EXPECTED_FILE_COUNT = 53;
const SHARD_LIMIT = 128 * 1024;
const LITERAL_LIMIT = 16 * 1024;

function fail(message) {
  throw new Error(message);
}

function parseArguments(argv) {
  let why3Root = resolve(PROJECT_ROOT, '..', 'why3');
  let mode = 'stdout';
  let directory = null;
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--why3-root') {
      if (!argv[index + 1]) fail('--why3-root requires a path');
      why3Root = resolve(argv[index + 1]);
      index += 1;
    } else if (argument === '--output-dir' || argument === '--check-dir') {
      if (!argv[index + 1]) fail(`${argument} requires a path`);
      if (directory !== null) fail('choose exactly one output mode');
      mode = argument === '--output-dir' ? 'output' : 'check';
      directory = resolve(argv[index + 1]);
      index += 1;
    } else {
      fail(`unknown argument: ${argument}`);
    }
  }
  return { why3Root, mode, directory };
}

function verifyWhy3Root(input) {
  const root = realpathSync(input);
  const commit = execFileSync(
    'git',
    ['-C', root, 'rev-parse', 'HEAD'],
    { encoding: 'utf8' },
  ).trim();
  if (commit !== EXPECTED_COMMIT) {
    fail(`expected Why3 ${EXPECTED_COMMIT}, got ${commit}`);
  }
  return root;
}

function walk(directory, root = directory, result = []) {
  for (const name of readdirSync(directory).sort()) {
    const path = join(directory, name);
    const metadata = statSync(path);
    if (metadata.isDirectory()) {
      walk(path, root, result);
    } else if (metadata.isFile() && name.endsWith('.mlw')) {
      result.push({
        path: relative(root, path).split(sep).join('/'),
        bytes: readFileSync(path),
      });
    }
  }
  return result;
}

function moonBytesLiteral(bytes) {
  let result = 'b"';
  for (const byte of bytes) {
    if (byte === 0x22) result += '\\"';
    else if (byte === 0x5c) result += '\\\\';
    else if (byte === 0x0a) result += '\\n';
    else if (byte === 0x0d) result += '\\r';
    else if (byte === 0x09) result += '\\t';
    else if (byte >= 0x20 && byte <= 0x7e) {
      result += String.fromCharCode(byte);
    } else {
      result += `\\x${byte.toString(16).padStart(2, '0')}`;
    }
  }
  return `${result}"`;
}

function sourceSegments(path) {
  return path
    .slice(0, -'.mlw'.length)
    .split('/')
    .map(segment => moonBytesLiteral(Buffer.from(segment, 'utf8')));
}

function sourceExpression(entry) {
  const chunks = [];
  for (let offset = 0; offset < entry.bytes.length; offset += LITERAL_LIMIT) {
    chunks.push(moonBytesLiteral(entry.bytes.subarray(offset, offset + LITERAL_LIMIT)));
  }
  return [
    '    @env.MemorySource::new(',
    `      @env.LibraryPath::new([${sourceSegments(entry.path).join(', ')}]),`,
    '      b"mlw",',
    '      embedded_source_bytes([',
    ...chunks.map(chunk => `        ${chunk},`),
    '      ]),',
    '    ),',
  ].join('\n');
}

function shardEntries(entries) {
  const shards = [];
  let current = [];
  let size = 0;
  for (const entry of entries) {
    if (current.length > 0 && size + entry.bytes.length > SHARD_LIMIT) {
      shards.push(current);
      current = [];
      size = 0;
    }
    current.push(entry);
    size += entry.bytes.length;
  }
  if (current.length > 0) shards.push(current);
  return shards;
}

function renderShard(index, entries) {
  const suffix = String(index).padStart(2, '0');
  return [
    '// SPDX-License-Identifier: LGPL-2.1-only WITH OCaml-LGPL-linking-exception',
    '// @generated by tools/why3_reference/generate_stdlib_sources.mjs; do not edit.',
    '',
    '///|',
    `fn raw_stdlib_sources_${suffix}() -> Array[@env.MemorySource] raise {`,
    '  [',
    ...entries.map(sourceExpression),
    '  ]',
    '}',
    '',
  ].join('\n');
}

function renderIndex(entries, shardCount) {
  const calls = Array.from(
    { length: shardCount },
    (_, index) => `raw_stdlib_sources_${String(index).padStart(2, '0')}()`,
  );
  const paths = entries.map(entry => {
    const segments = sourceSegments(entry.path).join(', ');
    return `    @env.LibraryPath::new([${segments}]),`;
  });
  return [
    '// SPDX-License-Identifier: LGPL-2.1-only WITH OCaml-LGPL-linking-exception',
    '// @generated by tools/why3_reference/generate_stdlib_sources.mjs; do not edit.',
    '',
    '///|',
    'fn embedded_source_bytes(chunks : ArrayView[Bytes]) -> Bytes {',
    '  let buffer = @buffer.Buffer()',
    '  for chunk in chunks {',
    '    buffer.write_bytes(chunk)',
    '  }',
    '  buffer.to_bytes()',
    '}',
    '',
    '///|',
    'pub fn embedded_stdlib_paths() -> Array[@env.LibraryPath] raise {',
    '  [',
    ...paths,
    '  ]',
    '}',
    '',
    '///|',
    'pub fn embedded_source_provider() -> @env.SourceProvider raise {',
    '  let sources : Array[@env.MemorySource] = []',
    ...calls.flatMap(call => [
      `  for source in ${call} {`,
      '    sources.push(source)',
      '  }',
    ]),
    '  @env.SourceProvider::memory(b"why3-1.7.2/stdlib", sources)',
    '}',
    '',
    '///|',
    '/// Creates a typed environment backed by the complete embedded Why3 1.7.2',
    "/// source library in the caller's compilation context.",
    'pub fn embedded_environment_in_context(',
    '  context : @identity.CompilationContext,',
    ') -> @environment.Environment raise {',
    '  @environment.Environment::with_source_in_context(',
    '    context,',
    '    embedded_source_provider(),',
    '  )',
    '}',
    '',
    '///|',
    '/// Creates a typed environment backed by the complete embedded Why3 1.7.2',
    '/// source library and a fresh compilation context.',
    'pub fn embedded_environment() -> @environment.Environment raise {',
    '  @environment.Environment::with_source(embedded_source_provider())',
    '}',
    '',
  ].join('\n');
}

function buildOutputs(root) {
  const entries = walk(join(root, 'stdlib'));
  if (entries.length !== EXPECTED_FILE_COUNT) {
    fail(`expected ${EXPECTED_FILE_COUNT} stdlib files, got ${entries.length}`);
  }
  const shards = shardEntries(entries);
  const outputs = new Map();
  shards.forEach((entries, index) => {
    outputs.set(
      `raw_source_${String(index).padStart(2, '0')}.mbt`,
      renderShard(index, entries),
    );
  });
  outputs.set('raw_sources.mbt', renderIndex(entries, shards.length));
  return outputs;
}

function managedNames(directory) {
  return readdirSync(directory)
    .filter(name => name === 'raw_sources.mbt' || /^raw_source_\d+\.mbt$/u.test(name))
    .sort();
}

function writeOutputs(directory, outputs) {
  mkdirSync(directory, { recursive: true });
  const expected = [...outputs.keys()].sort();
  const stale = managedNames(directory).filter(name => !outputs.has(name));
  if (stale.length > 0) fail(`stale generated raw sources: ${stale.join(', ')}`);
  for (const [name, contents] of outputs) {
    writeFileSync(join(directory, name), contents);
  }
  if (JSON.stringify(managedNames(directory)) !== JSON.stringify(expected)) {
    fail('generated raw-source file inventory mismatch');
  }
}

function checkOutputs(directory, outputs) {
  const expected = [...outputs.keys()].sort();
  if (JSON.stringify(managedNames(directory)) !== JSON.stringify(expected)) {
    fail('generated raw-source file inventory mismatch');
  }
  for (const [name, contents] of outputs) {
    if (readFileSync(join(directory, name), 'utf8') !== contents) {
      fail(`${name} is stale`);
    }
  }
}

const options = parseArguments(process.argv.slice(2));
const outputs = buildOutputs(verifyWhy3Root(options.why3Root));
if (options.mode === 'output') {
  writeOutputs(options.directory, outputs);
} else if (options.mode === 'check') {
  checkOutputs(options.directory, outputs);
} else {
  for (const [name, contents] of outputs) {
    process.stdout.write(`===== ${name} =====\n${contents}`);
  }
}
